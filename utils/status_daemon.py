#!/usr/bin/env python3
"""Track leading status numbers in direct subfolders without assessing them."""

import argparse
from collections import defaultdict
import logging
import math
import os
from pathlib import Path
import re
import signal
import tempfile
import threading


LOG = logging.getLogger("status-tracker")


def render_status(root: Path) -> str:
    groups = defaultdict(list, {number: [] for number in range(4)})
    unnumbered = []
    # One level only: root/STATUS.txt and grandchildren are never inputs.
    for folder in sorted(root.iterdir(), key=lambda path: (path.name.casefold(), path.name)):
        if not folder.is_dir():
            continue
        try:
            with (folder / "STATUS.txt").open(encoding="utf-8-sig") as source:
                first_line = source.readline()
        except FileNotFoundError:
            continue
        match = re.match(r"^([0-9]+)\b", first_line)
        if match:
            groups[int(match.group(1))].append(folder.name)
        else:
            unnumbered.append(folder.name)

    lines = [
        "Automatically generated by utils/status_daemon.py.",
        "Scope: STATUS.txt in direct subfolders only; numbers copied without reassessment.",
        "Edit each subfolder's STATUS.txt to change its group.",
        "",
    ]
    for number, folders in sorted(groups.items()):
        lines.append(f"{number} — {len(folders)} folders" if folders else f"{number} — none")
        lines.extend(f"  {folder}" for folder in folders)
        lines.append("")
    if unnumbered:
        lines.append(f"No leading integer — {len(unnumbered)} folders")
        lines.extend(f"  {folder}" for folder in unnumbered)
        lines.append("")
    lines.append(f"Total: {sum(map(len, groups.values()))} numbered status files.")
    return "\n".join(lines) + "\n"


def refresh(root: Path) -> bool:
    content = render_status(root)
    output = root / "STATUS.txt"
    try:
        if output.read_text(encoding="utf-8") == content:
            return False
    except FileNotFoundError:
        pass

    # Readers see either the complete previous list or the complete new list.
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=root, prefix=".status-tracker-", delete=False
        ) as stream:
            temporary = Path(stream.name)
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
            os.fchmod(stream.fileno(), 0o644)
        os.replace(temporary, output)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    LOG.info("Updated %s", output)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parent.parent,
        help="folder to track (default: parent of this script's utils directory)",
    )
    parser.add_argument("--interval", type=float, default=5, help="poll interval in seconds (default: 5)")
    parser.add_argument("--once", action="store_true", help="refresh once and exit")
    args = parser.parse_args()
    if not math.isfinite(args.interval) or args.interval <= 0:
        parser.error("--interval must be a finite positive number")
    root = args.root.resolve()
    if not root.is_dir():
        parser.error(f"root is not a directory: {root}")

    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    stopping = threading.Event()
    for signum in (signal.SIGINT, signal.SIGTERM):
        signal.signal(signum, lambda *_: stopping.set())
    LOG.info("Tracking direct subfolders of %s every %g seconds", root, args.interval)
    while not stopping.is_set():
        try:
            refresh(root)
        except (OSError, UnicodeError, ValueError):
            # An unreadable input must not replace a good list with a partial one.
            LOG.exception("Refresh failed; keeping the previous list")
            if args.once:
                return 1
        if args.once:
            break
        stopping.wait(args.interval)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
