#!/usr/bin/env python3
"""Summarize computed evidence without promoting mismatches to replication."""
from pathlib import Path
import hashlib
import json
import platform
import re
import subprocess
import sys
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def fmt(x):
    return f"{x:.5g}"


def main():
    df = pd.read_csv(ROOT/"results/main/metrics.csv")
    comp = pd.read_csv(ROOT/"results/main/paper_comparison.csv")
    meta = json.loads((ROOT/"results/main/metadata.json").read_text())
    validation = json.loads((ROOT/"results/validation/summary.json").read_text())
    sensitivity = json.loads((ROOT/"results/sensitivity/summary.json").read_text())
    tests = (ROOT/"results/tests.log").read_text().strip()
    main = df[(df.strategy != "STCO2") | (df.window == 4)]
    targets = pd.read_csv(ROOT/"sources/paper_risk_targets.csv")
    risk = targets.merge(main, on=["dataset", "strategy", "gamma"],
                         suffixes=("_target", "_reproduced"))
    for factor in ["MER", "alpha", "beta"]:
        risk[f"{factor}_error"] = risk[f"paper_{factor}_reproduced"]-risk[f"paper_{factor}_target"]
    risk.to_csv(ROOT/"results/main/paper_risk_comparison.csv", index=False)

    # Parse the three benchmark rows from the two halves of Table 5.
    text = (ROOT/"sources/paper.txt").read_text()
    table = text.split("Table 5. Cumulative wealth", 1)[1].split("B.6. Results", 1)[0]
    baseline_rows = []
    for strategy, label in [("UBAH", "U BAH"), ("BEST", "B EST"), ("BCRP", "B CRP")]:
        matches = re.findall(r"^\s*"+label+r"\s+([\d.]+(?:\s+[\d.]+){5})\s*$", table, re.M)
        assert len(matches) == 2
        for half, values in enumerate(matches):
            for j, value in enumerate(map(float, values.split())):
                baseline_rows.append({"dataset": ["NYSE(O)", "NYSE(N)", "TSE", "MSCI"][2*half+j//3],
                                      "strategy": strategy, "gamma": [0, .0025, .005][j%3],
                                      "paper_wealth": value})
    baselines = pd.DataFrame(baseline_rows)
    baselines.to_csv(ROOT/"sources/paper_baseline_targets.csv", index=False)
    bc = baselines.merge(main, on=["dataset", "strategy", "gamma"])
    bc["relative_error"] = bc.wealth/bc.paper_wealth-1
    bc.to_csv(ROOT/"results/main/baseline_comparison.csv", index=False)

    stco = df[df.strategy.str.startswith("STCO")]
    core = stco[stco.gamma.isin([0., .0025, .005])]
    nmatch = int(comp.within_1pct.sum())
    lines = [
        "STCO / PSGA: independent reproduction report",
        "============================================",
        "Computational record generated by Codex. Human scientific review is",
        "not recorded; this local report is not a submission-ready manuscript.",
        "",
        "Paper: Xiaoting Yao and Na Zhang (ICML 2026, PMLR 306).",
        "A Linearly Convergent Proximal Subgradient Algorithm for Sparse",
        "Portfolio Optimization with Transaction Cost.",
        "https://openreview.net/forum?id=yZAo4TPqhE",
        "Author source: https://github.com/Ting221/STCO",
        f"Pinned commit: {meta['upstream_commit']}",
        "",
        "OUTCOME",
        "The equations-based implementation, original-data experiments, and",
        "verification suite are complete. The published numerical tables were",
        "not replicated. No unpublished result or downloaded table is labeled",
        "as a computed result here.",
        f"Only {nmatch} of {len(comp)} proposed-method wealth cells are within 1% of Table 5",
        "under the declared main setting (STCO2 window 4).",
        "Window 5 sensitivity results are shown separately below.",
        "",
        "COMPLETED EXPERIMENTS",
        f"{len(df)} full-history strategy/rate/window runs; {len(stco)} proposed-method runs.",
        f"{len(core)} proposed-method runs at the paper's three table rates, including window sensitivity.",
        "Rates: "+", ".join(f"{v:.2%}" for v in meta['rates'])+".",
        "Original benchmark matrices, downloaded from the author repository:",
    ]
    for name, item in meta["datasets"].items():
        lines.append(f"  {name:8s} {item['shape'][0]:5d} days x {item['shape'][1]:2d} assets")
    lines += [
        "No substitute data, API downloads of recent prices, or synthetic market",
        "series are used in these main experiments.",
        "The K and c settings of Tables 2 and 3 are also evaluated, with STCO2",
        "window 4 throughout, in results/sensitivity/paper_comparison.csv.",
        f"This adds {sensitivity['new_backtests']} full-history backtests; {sensitivity['table_cells']} table cells",
        f"are compared, with {sensitivity['reused_main_cells']} cells reusing already computed main runs.",
        "",
        "TABLE 5: REPORTED VERSUS COMPUTED FINAL WEALTH",
        "All strategies start from wealth 1. STCO1 has no window parameter.",
        "Error is the relative error of the main setting, not log error.",
        "",
        f"{'Dataset':8s} {'Method':6s} {'Rate':6s} {'Paper':>12s} {'Main / w4':>12s} {'w5':>12s} {'Error':>10s}",
    ]
    for _, r in comp.iterrows():
        win5 = df[(df.dataset == r.dataset) & (df.strategy == "STCO2")
                  & np.isclose(df.gamma, r.gamma) & (df.window == 5)]
        w5 = fmt(win5.iloc[0].wealth) if r.strategy == "STCO2" and len(win5) else "-"
        lines.append(f"{r.dataset:8s} {r.strategy:6s} {r.gamma:6.2%} {fmt(r.paper_wealth):>12s} "
                     f"{fmt(r.wealth):>12s} {w5:>12s} {r.wealth_relative_error:>+9.1%}")
    lines += [
        "",
        "SOURCE AND SPECIFICATION DISCREPANCIES",
        "1. The uploaded STCO1_fun.m and STCO2_fun.m contain eta/tao terms and",
        "   a scalar multiplier, with no K, c, vector K-norm subgradient, or",
        "   PSGA outer loop. STCO1_run.m calls DENRPO1_fun, which is absent.",
        "   STCO2_run.m declares DENRPO2_run and calls absent DENRPO2_fun.",
        "   Therefore the uploaded code is not a runnable implementation of",
        "   the described PSGA-ADMM algorithm. This is a static source audit;",
        "   MATLAB/Octave is not installed and those scripts were not executed.",
        "2. Algorithm 2 line 6 uses inner w^j as the quadratic anchor, whereas",
        "   Lemma 3.7 and subproblem (12) require fixed outer w^k. We follow",
        "   equation (11), subproblem (12), and Lemma 3.7. The ADMM reference",
        "   includes a literal-pseudocode audit option, not used in main runs.",
        "3. Section 4 does not state STCO2's numerical window. Window 4 is",
        "   stated for the TCO2 comparator; we declare it as the main assumption",
        "   and test window 5. No window is fitted to individual table cells.",
        "4. The provided long-only BCRP benchmark is a separate independent",
        "   computation. Its NYSE(O) gross wealth is 250.597, versus 252.07",
        "   in the paper; its TSE gross wealth also differs. The BCRP optimizer",
        "   satisfies its first-order conditions. UBAH and BEST agree with",
        "   the reported rounded values to the precision of those tables.",
        "These discrepancies document uncertainty; they do not establish which",
        "particular implementation or specification produced the paper's tables.",
        "",
        "ALGORITHM AND ACCOUNTING",
        "We solve Q(w)=-q'w+lambda*||w-h||_1-c*sum_largest_K(w) over the simplex.",
        "c=8e-6, K=10, alpha=.0025, lambda=10*gamma, tolerance=1e-8, cap=1e8.",
        "The ADMM reference uses rho=.618. Main runs replace ADMM by an exact",
        "scalar-dual solution of the identical convex proximal subproblem.",
        "Event skipping jumps repeated affine proximal translations before the",
        "next zero, L1 kink, or top-K crossing. It keeps the fixed-step outer",
        "iteration mathematically; reference direct-iterate comparisons follow.",
        "Uniform initialization is reset in each daily optimization. Top-K ties",
        "use stable asset order. No hard threshold or K-sparsity repair is used.",
        "STCO2's startup window expands as in the uploaded prediction code.",
        "",
        "At each rebalance, theta solves theta+gamma*||h-theta*w||_1=1.",
        "Daily wealth multiplies by theta*(w'x), with no half-turnover factor.",
        "The initial purchase has h=0 and theta=1/(1+gamma). No liquidation",
        "cost is charged at the end. Decisions use only already observed prices.",
        "",
        "NUMERICAL VERIFICATION",
        tests,
        "Tests cover the prox against CVXPY/Clarabel; ADMM versus exact prox;",
        "direct versus accelerated PSGA; simplex and descent properties; causal",
        "predictions; transaction accounting; baseline identities; and LP oracles.",
    ]
    direct = validation["direct_market_audit"]
    station = validation["stationarity_audit"]
    oracle = validation["small_exact_penalty_oracle"]
    lines += [
        f"Market direct-iterate audit: {direct['cases']} daily problems, maximum weight",
        f"difference {direct['max_weight_error']:.3g}; stored-run difference",
        f"{direct['max_stored_weight_error']:.3g}. Prox evaluation reduction in this",
        f"sample: {direct['prox_evaluation_reduction']:.1f}x.",
        "Sampling: "+direct["sampling"],
        f"All saved proposed-method runs: maximum fixed-subgradient convex gap",
        f"{station['max_convex_gap']:.3g}; {station['days_gap_over_1e_6']} daily problems have gap >1e-6.",
        f"Maximum sampled relative fixed-point residual: {station['max_sampled_fixed_point_residual']:.3g}.",
        "The convex gap measures criticality for the selected top-K subgradient,",
        "not global optimality of the nonconvex problem.",
        f"Exhaustive small LP oracle: exact-penalty equivalence error",
        f"{oracle['global_equivalence_error']:.3g}; chosen c exceeds the sufficient bound.",
        f"PSGA's objective in that oracle case exceeds the global optimum by",
        f"{oracle['psga_global_objective_gap']:.6g}, illustrating its critical-point guarantee.",
        f"Direct descent trace: maximum objective increase",
        f"{validation['convergence']['max_objective_increase']:.3g}.",
        "The trace checks descent and convergence on one problem. It does not",
        "constitute an independent proof of the KL exponent or universal rate.",
        "",
        "SPARSITY AND CONVERGENCE LIMITS",
        f"Across {len(stco)} proposed-method full-history runs, nonconverged daily",
        f"optimizations: {int(stco.not_converged.sum())}.",
        f"Maximum simplex sum error: {stco.simplex_error.max():.3g}; minimum weight:",
        f"{stco.minimum_weight.min():.3g}.",
        f"At table rates, {int(core.days_over_k_after_initial.sum())} daily portfolios",
        "exceed K=10 after the initial portfolio, summed across all main and",
        "window-5 sensitivity runs. This count includes repeated days across",
        "settings; it is not a number of distinct dates.",
        "Support uses weight >1e-8; the paper does not define a support threshold.",
        "The initial uniform portfolio exceeds K on every benchmark and is",
        "included in the reported support mean/std, excluded from violation counts.",
        "The large-penalty theorem is sufficient, not necessary. Its global/local",
        "equivalence statement does not make every PSGA critical point globally",
        "optimal. The small experimental c is not treated as a hard cardinality",
        "constraint or a certificate that the theorem's bound holds.",
        "",
        "RISK METRICS AND BENCHMARK COVERAGE",
        "Appendix B.4's daily r=(gross-1)*theta omits direct transaction loss.",
        "For comparability, paper_MER/alpha/beta follow that formula. Standard",
        "net Sharpe and maximum drawdown use gross*theta-1 and realized wealth.",
        "Table 6 comparisons are in results/main/paper_risk_comparison.csv.",
        "Table 7 means/std and observed support are in paper_comparison.csv.",
        "Only UBAH, BEST, and BCRP are implemented as separate benchmark methods.",
        "The paper's other ten named competitor methods were not reimplemented;",
        "their published results are not reported as generated by this code.",
        "",
        "REPRODUCIBILITY",
        f"Python {meta['python']}; exact dependencies: requirements.lock.txt.",
        f"Main experiment elapsed time: {meta['elapsed_seconds']:.1f} seconds",
        "on this machine (includes initial compilation where applicable).",
        "Data/PDF checksums and BCRP residuals: results/main/metadata.json.",
        "Source/code checksums: sources/manifest.json.",
        "See README.md for commands, file formats, and implementation choices.",
        "Final charts are PNG and SVG in figures/.",
        "",
        "PROCEDURAL SOFTWARE REFERENCE",
        "Report provenance checks used the scientific-writing skill from Scientific",
        "Agent Skills. Kassis, T., Agarwal, V., He, Y., Patel, D., and Brueckner, A. M.",
        "(2026). Scientific Agent Skills: A Library of Procedural Knowledge for",
        "Research Agents. arXiv:2609.00065 (current record checked 2026-11-06).",
        "https://doi.org/10.48550/arXiv.2609.00065",
        "This procedural reference is not evidence for the STCO results.",
        "",
        "CONCLUSION",
        "The proposed model and equation-based PSGA are executable and checked",
        "on the original four benchmark datasets. The published table values",
        "remain unreplicated under the declared assumptions. Matching those",
        "values would require clarification or corrected experiment code from",
        "the authors, particularly the actual PSGA implementation and STCO2 window.",
    ]
    (ROOT/"REPORT.txt").write_text("\n".join(lines)+"\n")
    manifest = {"paper_url": "https://openreview.net/pdf?id=yZAo4TPqhE",
                "paper_license_as_listed": "CC BY 4.0",
                "paper_last_modified_as_listed": "2026-09-22",
                "author_repository": "https://github.com/Ting221/STCO",
                "author_commit": meta["upstream_commit"],
                "author_code_license": "No license file present at pinned commit; upstream retained as a separate checkout.",
                "sha256": {}}
    files = ([ROOT/"sources/paper.pdf", ROOT/"sources/paper.txt"]
             + sorted((ROOT/"stco").glob("*.py"))
             + sorted((ROOT/"scripts").glob("*.py"))
             + sorted((ROOT/"tests").glob("*.py"))
             + sorted((ROOT/"upstream/STCO-code").glob("*")))
    manifest["sha256"] = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                          for p in files if p.is_file()}
    (ROOT/"sources/manifest.json").write_text(json.dumps(manifest, indent=2)+"\n")
    status = {"implementation": "complete", "experiments": "complete",
              "paper_numerical_replication": "not achieved",
              "wealth_cells_within_1pct": nmatch, "wealth_cells_compared": len(comp),
              "tests": tests.splitlines()[-1], "computed_runs": len(df),
              "proposed_method_runs": len(stco),
              "additional_sensitivity_backtests": sensitivity["new_backtests"],
              "sensitivity_table_cells": sensitivity["table_cells"], "report": "REPORT.txt"}
    (ROOT/"reproduction_status.json").write_text(json.dumps(status, indent=2)+"\n")
    print(json.dumps(status, indent=2))


if __name__ == "__main__":
    main()
